"""Rebuilds the question pages of index.html from the shared question list.

The questions live in src/lib/venue-checklist-questions.ts (the phone checklist reads
the same file). To change a question, edit that file, then from the repo root run:

    npx tsx docs/venue-checklist/v4/dump-questions.ts > /tmp/questions.json
    python3 docs/venue-checklist/v4/build.py /tmp/questions.json

Everything between <!-- QUESTIONS START --> and <!-- QUESTIONS END --> is replaced.
"""
import html
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
sections = {s["id"]: s for s in json.load(open(sys.argv[1]))}
esc = lambda text: html.escape(text, quote=False)

VERDICT = '<div class="verdict"><p class="label">Verdict</p><span>Clear</span><span>Needs follow-up</span><span>Dealbreaker</span></div>'
ANSWER = '<div class="ans"><span>Answer</span><i></i><span>Who said it</span><i></i></div>'


def question(q):
    if not q.get("star"):
        tip = f'<span class="w tip">{esc(q["tip"])}</span>' if q.get("tip") else ""
        return f'      <li><span class="t">{esc(q["text"])}</span>{tip}</li>'
    return f'      <li class="s"><span class="t">{esc(q["text"])}</span><span class="w">{esc(q["why"])}</span>{ANSWER}</li>'


def section(sid, verdict=True):
    s = sections[sid]
    out = ['  <div class="sec">', f'    <h3><span>{s["num"]}</span>{esc(s["title"])}</h3>']
    if s.get("why"):
        out.append(f'    <p class="why">{esc(s["why"])}</p>')
    out.append('    <ul class="q">' if s.get("why") else '    <ul class="q" style="margin-top:6pt">')
    out += [question(q) for q in s["questions"]]
    out.append('    </ul>')
    if s.get("planner"):
        out.append(f'    <p class="designer"><b>For your planner:</b> {esc(s["planner"])}</p>')
    if verdict:
        out.append(f'    {VERDICT}')
    out.append('  </div>')
    return "\n".join(out)


def page(ids, notes=True, comment=""):
    body = "\n".join(section(i) for i in ids)
    tail = '\n  <div class="notes"><p class="label">Notes</p><div></div></div>' if notes else ""
    return f'<!-- {comment} -->\n<section class="page pad">\n{body}{tail}\n</section>\n'


stars = [q for sid, s in sections.items() if not s.get("multicultural") for q in s["questions"] if q.get("star")]
top10 = "\n".join(
    f'    <li><span>{n:02d}</span><div><b>{esc(q["text"])}</b>{esc(q["why"])}</div></li>' for n, q in enumerate(stars, 1)
)

mc_one = "\n".join(section(i, verdict=False) for i in ["mc-ceremonies", "mc-fire"])
mc_two = "\n".join(section(i, verdict=False) for i in ["mc-cuisine", "mc-procession", "mc-timeline"])

generated = f"""<!-- QUESTIONS START (generated by build.py: edit src/lib/venue-checklist-questions.ts, not this block) -->
<!-- The ten dealbreakers -->
<section class="page pad top10">
  <p class="kicker">If you only ask ten</p>
  <h2>10 questions to <em>never leave a tour without</em></h2>
  <p class="lead">Each one is starred <span class="star">★</span> in the checklist, with room for the answer and the name of the person who gave it.</p>
  <ol class="steps">
{top10}
  </ol>
</section>

<!-- The one rule + red flags -->
<section class="page">
  <div class="pad" style="padding-bottom:0">
    <p class="kicker">The one rule</p>
    <h2>“We’re flexible” <em>is not a yes</em></h2>
    <p class="lead" style="max-width:5.9in">Here is how it can happen. On the tour, you mention that your caterer will cook on site, and the coordinator smiles and says, “We’re very flexible.” Months later, the contract arrives, and it says outside food must arrive fully prepared. Nothing was promised in writing, so nothing was promised.</p>
    <div class="note" style="margin-top:4pt"><p class="label">Before you sign</p><p>If a promise affects your ceremony, décor, food, music, parking, guest count, budget, or timeline, ask for it in writing.</p></div>
    <p class="kicker" style="margin-top:22pt">If you hear this, slow down</p>
    <ul class="flags">
      <li>“We’re flexible,” with nothing in writing behind it.</li>
      <li>Only an hour or two to set up before guests arrive.</li>
      <li>The rain-backup space can’t hold everyone, or you wouldn’t want to use it.</li>
      <li>The quote leaves out the service charge, tax, or overtime.</li>
    </ul>
  </div>
  <div class="band-bottom" style="height:3.1in"><img src="assets/rule-floral-arch.jpg" alt="" style="object-position:50% 60%"></div>
</section>

@@HOWTO@@
{page(["hours", "capacity"], notes=False, comment="01–02")}
{page(["alcohol", "catering", "rentals"], notes=False, comment="03–05")}
{page(["decor"], comment="06")}
{page(["power", "parking"], comment="07–08")}
{page(["cost"], comment="09")}
<!-- Multicultural chapter, part one (multicultural edition only) -->
<section class="page mc-only">
  <div class="band-top" style="height:2.8in"><img src="assets/mc-chapter-couple.jpg" alt="" style="object-position:50% 22%"></div>
  <div class="pad" style="padding-top:3.15in;height:100%">
    <p class="kicker">Section 10 · For multicultural weddings</p>
    <h2>Questions for <em>Multicultural Weddings</em></h2>
    <p class="lead" style="margin-bottom:10pt">A venue saying it hosts multicultural weddings isn’t the same as confirming it can host yours. Ask only what matches your traditions, and name each one.</p>
{mc_one}
  {VERDICT}
  </div>
</section>

<!-- Multicultural chapter, part two (multicultural edition only) -->
<section class="page pad mc-only">
{mc_two}
  {VERDICT}
  <div class="notes"><p class="label">Notes · your traditions and what the venue said</p><div></div></div>
</section>

<!-- Chase list + before you sign -->
<section class="page pad">
  <p class="kicker">After the tour</p>
  <h2>Your <em>Chase List</em></h2>
  <p class="lead" style="margin-bottom:10pt">Copy every question you marked with a slash: asked, but not yet in writing. Email the list to the venue, and check each one off as it comes back.</p>
  <table class="chase">
    <thead><tr><th>Question</th><th>Who said it</th><th>In writing</th></tr></thead>
    <tbody></tbody>
  </table>
  <div class="final">
    <p class="kicker" style="margin-bottom:8pt">The last step</p>
    <h3>Before You Sign</h3>
    <ol class="steps">
      <li><span>01</span><div>Get a complete, itemized quote.</div></li>
      <li><span>02</span><div>Have your designer check load-in, rigging, and power.</div></li>
      <li><span>03</span><div>Make sure every approval you were given is in the contract.</div></li>
    </ol>
  </div>
</section>
<!-- QUESTIONS END -->"""

index = HERE / "index.html"
source = index.read_text()
start = source.index("<!-- QUESTIONS START")
end = source.index("<!-- QUESTIONS END -->") + len("<!-- QUESTIONS END -->")
howto = source[source.index("<!-- How to use + what to bring -->"):source.index("</section>", source.index("<!-- How to use + what to bring -->")) + len("</section>")]
index.write_text(source[:start] + generated.replace("@@HOWTO@@", howto) + source[end:])
print("questions:", sum(len(s["questions"]) for s in sections.values() if not s.get("multicultural")), "standard,",
      sum(len(s["questions"]) for s in sections.values()), "multicultural; stars:", len(stars))
